"""
Packet 1 Golden Practice Scorer Test

Tests golden_practice_v1.json fixture with real scorer.
Oracle is hand-calculated, NOT generated by scorer.
Validates score_exact as string format and compares against hand oracle.
"""
import pytest
import json
from pathlib import Path
from fractions import Fraction


@pytest.mark.asyncio
async def test_golden_practice_scorer():
    """Test golden practice fixture with real scorer"""
    # Load golden fixture
    golden_path = Path(__file__).resolve().parents[2] / 'docs' / 'packet1' / 'golden_practice_v1.json'
    golden = json.loads(golden_path.read_text())
    
    # Import scorer
    import sys
    sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'backend'))
    from tejas_core import score_attempt
    
    # Build attempt from golden cases
    questions = []
    answers = {}
    
    for i, case in enumerate(golden["cases"]):
        qid = f"q{i+1}"
        questions.append({
            "id": qid,
            "number": i + 1,
            "type": case["kind"],
            "answer": case["key"],
            "disposition": "standard",
            "text": f"Question {i+1}",
            "options": {"1": "A", "2": "B"} if case["kind"] == "mcq" else {}
        })
        if case["response"]:
            answers[qid] = {
                "value": case["response"],
                "timestamp": 1234567890.0  # Synthetic timestamp
            }
    
    attempt = {
        "id": "golden-test-attempt",
        "questions": questions,
        "answers": answers,
        "rules": golden["rules"],
        "status": "completed",
        "started_at": 1234567890.0,
        "submitted_at": 1234567900.0
    }
    
    # Score attempt
    result = score_attempt(attempt)
    
    # Verify each case
    for i, case in enumerate(golden["cases"]):
        scored_q = result["questions"][i]
        
        # Check outcome
        assert scored_q["outcome"] == case["expected_outcome"], \
            f"Case {case['id']}: expected {case['expected_outcome']}, got {scored_q['outcome']}"
        
        # Check marks - scorer returns integer marks, not exact fraction
        # Compare against hand oracle using Fraction
        actual_marks = scored_q["marks"]
        expected_fraction = Fraction(case["expected_numerator"], case["expected_denominator"])
        expected_marks = int(expected_fraction) if expected_fraction.denominator == 1 else float(expected_fraction)
        
        assert actual_marks == expected_marks, \
            f"Case {case['id']}: expected {expected_marks}, got {actual_marks}"
        
        print(f"✓ Case {case['id']}: {case['expected_outcome']} = {actual_marks} (oracle: {case['expected_numerator']}/{case['expected_denominator']})")
    
    # Verify total - compare against hand oracle
    summary = result["summary"]
    actual_total = summary["score"]
    expected_total_fraction = Fraction(golden["expected_total_numerator"], golden["expected_total_denominator"])
    expected_total = int(expected_total_fraction) if expected_total_fraction.denominator == 1 else float(expected_total_fraction)
    
    assert actual_total == expected_total, \
        f"Expected total {expected_total}, got {actual_total}"
    
    # Verify summary.score_exact string
    assert "score_exact" in summary
    assert isinstance(summary["score_exact"], str)
    # For integer scores, score_exact should be string representation
    assert summary["score_exact"] == str(expected_total)
    
    print(f"✓ Total: {actual_total} (hand-calculated oracle: {golden['oracle']})")
    print(f"✓ Golden practice fixture passed with real scorer")


if __name__ == "__main__":
    pytest.main([__file__, "-v", "-s"])
