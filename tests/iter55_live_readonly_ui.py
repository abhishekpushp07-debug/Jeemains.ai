import json, time
from pathlib import Path

results=[]
events=[]
statuses=[]
def requested(r):
    if '/api/jl/' in r.url:
        path=r.url.split('/api/jl')[-1]
        events.append({'path':path if any(s in path for s in ['/pyq/','/catalogue?','/my/tests?','/auth/']) else 'other-read','method':r.method,'at':time.monotonic()})
page.on('request',requested)
page.on('response',lambda r: statuses.append({'path':r.url.split('/api/jl')[-1].split('?')[0],'status':r.status}) if '/api/jl/' in r.url else None)
async def mark(label,start,prefix):
    item={'label':label,'visible_ms':round((time.monotonic()-start)*1000),'request_count':sum(r['at']>=start and r['path'].startswith(prefix) for r in events)}
    results.append(item)
    print('METRIC',json.dumps(item))
