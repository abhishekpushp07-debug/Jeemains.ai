async def run_test(page, output_dir, page_url):
    import re, json, time
    from pathlib import Path
    results=[]
    requests=[]
    login_status=[]
    page.on('request', lambda r: requests.append({'path':r.url.split('/api/jl')[-1].split('?')[0], 'method':r.method,'at':time.monotonic()}) if '/api/jl/' in r.url else None)
    page.on('response', lambda r: login_status.append(r.status) if '/api/jl/auth/phone' in r.url else None)
    async def metric(label, start, prefix):
        record={'label':label,'visible_ms':round((time.monotonic()-start)*1000),'requests':sum(1 for r in requests if r['at']>=start and r['path'].startswith(prefix))}
        results.append(record)
        print('METRIC',json.dumps(record))
    try:
        await page.set_viewport_size({'width':390,'height':844})
        await page.locator('[data-testid="entry-phone-input"]').wait_for(timeout=40000)
        await page.wait_for_timeout(1500)
        creds=Path('/app/memory/test_credentials.md').read_text()
        pair=re.search(r'User-approved live canonical test phone: `([0-9]+)`, PIN: `([0-9]+)`',creds)
        assert pair, 'Approved credentials unavailable; no login attempted'
        await page.locator('[data-testid="entry-phone-input"]').fill(pair.group(1))
        await page.locator('[data-testid="entry-pin-input"]').fill(pair.group(2))
        button=page.locator('[data-testid="entry-continue-button"]')
        await page.wait_for_function("()=>{let b=document.querySelector('[data-testid=entry-continue-button]');return b && b.getAttribute('aria-disabled')!=='true' && !b.disabled}",timeout=40000)
        await button.click(force=True)
        await page.wait_for_timeout(2000)
        assert not any(s in [401,429] for s in login_status), 'Login rejected; stopped without retry'
        await page.locator('[data-testid="home-screen"]').wait_for(timeout=40000)
        print('PASS login once',login_status)
        print('HOME artwork',await page.locator('[data-testid="home-exam-grid"] img').evaluate_all('(els)=>els.map(e=>({loaded:e.complete&&e.naturalWidth>0}))'))
        await page.screenshot(path='/app/test_reports/artifacts_iter55/live/automation_output/20261028_171109_b8c8ad21f94c/home390.jpeg', type="jpeg", quality=40, full_page=False)
        await page.set_viewport_size({'width':320,'height':844})
        print('HOME320 overflow',await page.evaluate('document.documentElement.scrollWidth>innerWidth'))
        await page.screenshot(path='/app/test_reports/artifacts_iter55/live/automation_output/20261028_171109_b8c8ad21f94c/home320.jpeg', type="jpeg", quality=40, full_page=False)
        await page.set_viewport_size({'width':390,'height':844})
        t=time.monotonic()
        await page.locator('[data-testid="home-tile-jee-main"]').click(force=True)
        if await page.locator('[data-testid="exam-destination-pyq"]').count():
            await page.locator('[data-testid="exam-destination-pyq"]').click(force=True)
        await page.locator('[data-testid="pyq-total"]').wait_for(timeout=40000)
        await page.locator('[data-testid^="pyq-paper-"]').first.wait_for(timeout=10000)
        await metric('PYQ cold navigation',t,'/pyq/jee-main')
        print('PYQ',await page.locator('[data-testid="pyq-total"]').inner_text())
        await page.locator('[data-testid="pyq-back-button"]').click(force=True)
        t=time.monotonic()
        if await page.locator('[data-testid="home-tile-jee-main"]').count():
            await page.locator('[data-testid="home-tile-jee-main"]').click(force=True)
        else:
            await page.locator('[data-testid="exam-destination-pyq"]').click(force=True)
        await page.locator('[data-testid="pyq-total"]').wait_for(timeout=10000)
        await metric('PYQ warm revisit',t,'/pyq/jee-main')
        await page.set_viewport_size({'width':320,'height':844})
        print('PYQ320 overflow',await page.evaluate('document.documentElement.scrollWidth>innerWidth'))
        await page.screenshot(path='/app/test_reports/artifacts_iter55/live/automation_output/20261028_171109_b8c8ad21f94c/pyq320.jpeg', type="jpeg", quality=40, full_page=False)
        await page.set_viewport_size({'width':390,'height':844})
        await page.locator('[data-testid="pyq-back-button"]').click(force=True)
        if not await page.locator('[data-testid="home-tile-bitsat"]').count():
            await page.locator('[data-testid="tab-index"]').click(force=True)
        t=time.monotonic()
        await page.locator('[data-testid="home-tile-bitsat"]').click(force=True)
        await page.locator('[data-testid="exam-destination-mocks"]').click(force=True)
        await page.locator('[data-testid="catalogue-count"]').wait_for(timeout=40000)
        await page.locator('[data-testid^="set-title-"]').first.wait_for(timeout=10000)
        await metric('BITSAT cold navigation',t,'/exam-navigation/bitsat/catalogue')
        print('BITSAT',await page.locator('[data-testid="catalogue-count"]').inner_text())
        await page.locator('[data-testid="catalogue-next-page"]').scroll_into_view_if_needed()
        t=time.monotonic()
        await page.locator('[data-testid="catalogue-next-page"]').click(force=True)
        await page.wait_for_function("()=>document.querySelector('[data-testid=catalogue-page]')?.textContent.startsWith('2 /')",timeout=40000)
        await page.locator('[data-testid^="set-title-"]').first.wait_for(timeout=40000)
        await metric('BITSAT page2',t,'/exam-navigation/bitsat/catalogue')
        t=time.monotonic()
        await page.locator('[data-testid="catalogue-search-input"]').fill('Mock 1')
        await page.wait_for_timeout(1000)
        await page.locator('[data-testid="catalogue-count"]').wait_for(timeout=40000)
        print('SEARCH count',await page.locator('[data-testid="catalogue-count"]').inner_text())
        print('SEARCH page',await page.locator('[data-testid="catalogue-page"]').inner_text() if await page.locator('[data-testid="catalogue-page"]').count() else 'single page')
        await metric('BITSAT search (includes debounce wait)',t,'/exam-navigation/bitsat/catalogue')
        await page.locator('[data-testid="catalogue-clear-search"]').click(force=True)
        await page.wait_for_timeout(1500)
        print('PASS search reset',await page.locator('[data-testid="catalogue-page"]').inner_text())
        await page.locator('[data-testid="catalogue-back-button"]').click(force=True)
        t=time.monotonic()
        await page.locator('[data-testid="exam-destination-mocks"]').click(force=True)
        await page.locator('[data-testid="catalogue-count"]').wait_for(timeout=10000)
        await metric('BITSAT warm revisit',t,'/exam-navigation/bitsat/catalogue')
        await page.locator('[data-testid="catalogue-back-button"]').click(force=True)
        await page.locator('[data-testid="tab-tests"]').click(force=True)
        await page.locator('[data-testid="my-tests-count-progress"]').wait_for(timeout=40000)
        print('PASS MyTests progress')
        for tab in ['saved','completed']:
            t=time.monotonic()
            await page.locator('[data-testid="my-tests-tab-'+tab+'"]').click(force=True)
            await page.locator('[data-testid="my-tests-count-'+tab+'"]').wait_for(timeout=40000)
            await page.wait_for_timeout(500)
            await metric('MyTests '+tab,t,'/my/tests')
        await page.screenshot(path='/app/test_reports/artifacts_iter55/live/automation_output/20261028_171109_b8c8ad21f94c/mytests390.jpeg', type="jpeg", quality=40, full_page=False)
        await page.route('**/api/jl/my/tests?**',lambda route: route.fulfill(status=503,content_type='application/json',body='{"detail":"Isolated network failure"}'))
        await page.locator('[data-testid="tab-index"]').click(force=True)
        await page.locator('[data-testid="tab-tests"]').click(force=True)
        await page.locator('[data-testid="my-tests-error"]').wait_for(timeout=10000)
        print('PASS isolated503 retains completed rows',await page.locator('[data-testid^="attempt-container-"]').count())
        await page.unroute('**/api/jl/my/tests?**')
        await page.route('**/api/jl/auth/session',lambda route: route.fulfill(status=503,content_type='application/json',body='{"detail":"Isolated network failure"}'))
        await page.evaluate("document.dispatchEvent(new Event('visibilitychange'))")
        await page.wait_for_timeout(1500)
        print('Verified user still mounted',await page.locator('[data-testid="my-tests-screen"]').count())
        await page.unroute('**/api/jl/auth/session')
        print('JL writes',[(r['path'],r['method']) for r in requests if r['method'] not in ['GET','HEAD']])
    except Exception as e:
        print('FAIL live step',str(e))
        print('CURRENT controls',await page.locator('[data-testid]').evaluate_all('(els)=>els.map(e=>e.dataset.testid).filter(s=>!s.includes("attempt")&&!s.includes("paper")).slice(0,90)'))
    finally:
        error_text=await page.evaluate("""() => {const errorElements = Array.from(document.querySelectorAll('.error, [class*="error"], [id*="error"]'));return errorElements.map(el => el.textContent).join(', ');} """)
        print('Found error message: '+error_text if error_text else 'No error messages found on the page')
        Path('/app/test_reports/artifacts_iter55').mkdir(parents=True,exist_ok=True)
        Path('/app/test_reports/artifacts_iter55/live_metrics.json').write_text(json.dumps(results,indent=2))
